    /**
     * Valida que los campos de texto principales no estén vacíos y
     * aplica reglas específicas como división por cero o índice de raíz.
     */
    private boolean validarCampos(java.awt.event.ActionEvent evt) {
        if (txtValor1.getText().trim().length() <= 0) {
            JOptionPane.showMessageDialog(null, "Favor ingresar valor 1, porque el campo esta vacio");
            txtValor1.requestFocus();
            return false;

        } else if (txtValor2.getText().trim().length() <= 0) {
            JOptionPane.showMessageDialog(null, "Favor ingresar valor 2, porque el campo esta vacio");
            txtValor2.requestFocus();
            return false;
        }
        // Validación de división por cero
        if (evt.getSource() == btnDividir) {
            double numero = Double.parseDouble(txtValor2.getText().trim());
            if (numero == 0) {

                JOptionPane.showMessageDialog(null, "Favor ingresar en el valor 2 un numero diferente a 0");
                txtValor2.setText("1");
                txtValor2.requestFocus();

                return false;
            }
        }
        // Validación para raíz (requiere valor 2 igual a 2)
        if (evt.getSource() == btnRaiz) {
            double numero = Double.parseDouble(txtValor2.getText().trim());
            if (numero != 2) {

                JOptionPane.showMessageDialog(null, "Favor ingresar en el valor 2 el numero 2");
                txtValor2.setText("2");
                txtValor2.requestFocus();

                return false;
            }
        }

        return true;
    }
    /**
     * Valida que el campo de temperatura tenga un valor ingresado.
     */
    private boolean validarCampoTemperatura(java.awt.event.ActionEvent evt) {
        if (txtTemperatura.getText().trim().length() <= 0) {
            JOptionPane.showMessageDialog(null, "Favor ingresar valor 1, porque el campo esta vacio");
            txtTemperatura.requestFocus();
            return false;
        }
        
        return true;
        
    }


