    /**
     * Manejador del evento clic en el botón "Calcular Resultado".
     * Valida las entradas, suma las notas y determina la condición final.
     */
    private void btnResultadoActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnResultadoActionPerformed
        if (!validarCampos()) {
            return;
        }
        int notaTotal = sumarValores();
        if(notaTotal <= 100){
        txtNotaTotal.setText(""+notaTotal);
        }
        else{
            return;
        }
        
        // Evaluar si el estudiante aprueba (60 puntos o más)
        if(notaTotal >= 60){
            txtResultado.setText("Aprobado");
        }
        
        else{
            txtResultado.setText("Reprobado");
        }
    }//GEN-LAST:event_btnResultadoActionPerformed
    /**
     * Valida que los campos personales no estén vacíos y que las notas
     * cumplan con los rangos permitidos.
     * 
     * @return true si todos los datos son válidos, false en caso contrario.
     */
    private boolean validarCampos() {
        
        String textoNombreCompleto = txtNombreCompleto.getText().trim();
        if (textoNombreCompleto.isEmpty()) {
            JOptionPane.showMessageDialog(null, "El campo de nombre completo no puede estar vacío.");
            txtNombreCompleto.requestFocus();
            return false;
        }

        String textoMatricula = txtMatricula.getText().trim();
        if (textoMatricula.isEmpty()) {
            JOptionPane.showMessageDialog(null, "El campo de Matricula no puede estar vacío.");
            txtMatricula.requestFocus();
            return false;
        }

        String textoCarrera = txtCarrera.getText().trim();
        if (textoCarrera.isEmpty()) {
            JOptionPane.showMessageDialog(null, "El campo de Carrera no puede estar vacío.");
            txtCarrera.requestFocus();
            return false;
        }

        String textonotaPractica = txtnotaPracticas.getText().trim();
        if (textonotaPractica.isEmpty()) {
            JOptionPane.showMessageDialog(null, "El campo de práctica no puede estar vacío.");
            return false;
        }
       
        
        String textonotaAsignaciones = txtnotaAsignaciones.getText().trim();
        if (textonotaAsignaciones.isEmpty()) {
            JOptionPane.showMessageDialog(null, "El campo de asignación no puede estar vacío.");
            return false;
        }
        
        
        String textonotaParciales = txtnotaParciales.getText().trim();
        if (textonotaParciales.isEmpty()) {
            JOptionPane.showMessageDialog(null, "El campo de parciales no puede estar vacío.");
            return false;
        }
        
        
        String textonotaExamenFinal = txtnotaExamenFinal.getText().trim();
        if (textonotaExamenFinal.isEmpty()) {
            JOptionPane.showMessageDialog(null, "El campo de examen final no puede estar vacío.");
            return false;
        }
        // Validación de límites máximos por rubro
        if (!validarNota(txtnotaPracticas, "prácticas", 40)) {
            return false;
        }
        
        
        if (!validarNota(txtnotaAsignaciones, "asignaciones", 20)) {
            return false;
        }

       
        if (!validarNota(txtnotaParciales, "parciales", 20)) {
            return false;
        }

        
        if (!validarNota(txtnotaExamenFinal, "examen final", 20)) {
            return false;
        }

        return true;
       

    }
    /**
     * Comprueba si el valor de un campo numérico está dentro del rango 0 a máximo.
     */
    private boolean validarNota(javax.swing.JTextField campo, String nombreCampo, int maximo) {
        String texto = campo.getText().trim();

        if (texto.isEmpty()) {
            JOptionPane.showMessageDialog(this, "El campo de " + nombreCampo + " no puede estar vacío.");
            campo.requestFocus();
            return false;
        }

        try {
            int nota = Integer.parseInt(texto);
            if (nota < 0 || nota > maximo) {
                JOptionPane.showMessageDialog(this, "La nota de " + nombreCampo + " debe estar entre 0 y " + maximo + ".");
                campo.requestFocus();
                return false;
            }
        } catch (NumberFormatException e) {
            JOptionPane.showMessageDialog(this, "Ingrese un número entero válido en " + nombreCampo + ".");
            campo.requestFocus();
            return false;
        }

        return true;
    }
    /**
     * Calcula la suma de todos los campos numéricos de calificaciones.
     * 
     * @return suma total en puntos acumulados.
     */
    private int sumarValores(){
        int notatextoPracticas = Integer.parseInt(txtnotaPracticas.getText().trim());
        int notatextoAsignaciones = Integer.parseInt(txtnotaAsignaciones.getText().trim());
        int notatextoParciales = Integer.parseInt(txtnotaParciales.getText().trim());
        int notatextoExamenFinal = Integer.parseInt(txtnotaExamenFinal.getText().trim());
        
        int notaTotal = notatextoPracticas + notatextoAsignaciones + notatextoParciales + notatextoExamenFinal;
        
        return notaTotal;
        
    }
